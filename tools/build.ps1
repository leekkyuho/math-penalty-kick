# 1) assets/images/seat-masks/*.png -> js/seat-masks.js
#    (the crowd reads mask pixels; inlined data URIs keep that working when index.html is opened from a local folder)
# 2) index.html + css + js + assets -> 오프라인용/math-penalty.html (one file, everything inlined)
# usage (repo root): powershell -ExecutionPolicy Bypass -File tools\build.ps1
$root = Split-Path $PSScriptRoot -Parent
$u8 = New-Object Text.UTF8Encoding $false
function Read([string]$p) { [IO.File]::ReadAllText((Join-Path $root $p), [Text.Encoding]::UTF8) }
function Uri([string]$p) {
  $type = if ($p.EndsWith(".jpg")) { "image/jpeg" } else { "image/png" }
  "data:$type;base64," + [Convert]::ToBase64String([IO.File]::ReadAllBytes((Join-Path $root $p)))
}

$m = "assets/images/seat-masks"
$masks = "// generated by tools/build.ps1 from $m/*.png - do not edit`n" +
  "window.SEAT_MASKS = {`n" +
  "  L: '" + (Uri "$m/left.png") + "',`n" +
  "  R: '" + (Uri "$m/right.png") + "',`n" +
  "  C: '" + (Uri "$m/center.png") + "'`n};`n"
[IO.File]::WriteAllText((Join-Path $root "js\seat-masks.js"), $masks, $u8)

$html = Read "index.html"
$html = $html.Replace('<link rel="stylesheet" href="css/style.css">', "<style>`n" + (Read "css/style.css") + "</style>")
$html = $html.Replace('<script src="js/seat-masks.js"></script>', "<script>`n" + $masks + "</script>")
$html = $html.Replace('<script src="js/game.js"></script>', "<script>`n" + (Read "js/game.js") + "</script>")
foreach ($f in "bg.jpg", "ball.png", "k_body.png", "k_armL.png", "k_armR.png") { $html = $html.Replace("assets/images/$f", (Uri "assets/images/$f")) }
if ($html -match 'href="(css|js|assets)/' -or $html -match 'src="(js|assets)/') { throw "external reference left in offline build" }

$dir = Join-Path $root "오프라인용"
New-Item -ItemType Directory -Force $dir | Out-Null
$out = Join-Path $dir "math-penalty.html"
[IO.File]::WriteAllText($out, $html, $u8)
"{0}  {1:N0} bytes" -f $out, (Get-Item $out).Length
